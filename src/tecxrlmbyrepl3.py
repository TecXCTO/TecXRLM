import asyncio
from rlm import RLM

async def main():
    # Large target corpus data context stored securely inside the REPL environment
    large_context = (
        "Proprietary Analytics Corpus V4. Project Omega infrastructure metrics: "
        "Server architecture is running on AWS clusters. Security standards conform "
        "to SOC2 frameworks. Primary core relational database relies on PostgreSQL 15."
    )
    
    query = "Search through the provided dataset context variables, extract infrastructure compliance data, and compile an evaluation."

    print("🛡️ Bootstrapping Secure Isolated RLM Cluster Environment...")
    
    # Configure the framework to spawn dynamic docker nodes for execution safety
    rlm = RLM(
        # 1. Primary Model: Handles heavy semantic orchestration, planning, and code writing
        backend="openai",
        backend_kwargs={
            "model_name": "gpt-5-nano",
            "api_key": "YOUR_OPENAI_API_KEY"
        },
        
        # 2. Advanced Security Sandbox Separation
        environment="docker", 
        environment_kwargs={
            "image": "python:3.11-slim", # Spawns a sandboxed Linux engine separated from host OS
            "init_globals": {"large_context": large_context}
        },
        
        # 3. Secondary Reasoner Offloading: Spawns specialized workers for high-speed sub-tasks
        sub_model_backend="openai",
        sub_model_name="gpt-4o-mini",
        
        verbose=True # Generates step-by-step diagnostic text logs in terminal output
    )

    print("⏳ Dispatching Asynchronous Compute Loop Request...")
    try:
        # Run the tracking trajectory loops over the docker image container layer
        result = await rlm.completion(prompt=query)
        
        print("\n✨ [CONTAINERIZED EXECUTION SUCCESSFUL] REPORT SUMMARY:")
        print(result.response)
        
        print(f"\n📊 Performance Logs -> Sub-Model Iterations: {result.total_calls} | Total Processed Tokens: {result.total_tokens}")
        
    except Exception as e:
        print(f"❌ Sandbox Cluster Fault: {str(e)}")

if __name__ == "__main__":
    asyncio.run(main())

